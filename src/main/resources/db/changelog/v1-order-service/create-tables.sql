--changeset Lmncrt:001-create-tables
CREATE TABLE public.items (
    id bigint generated by default as identity primary key,
    item_name varchar(255),
    item_count integer not null,
    item_amount numeric(12,2)
);

CREATE TABLE public.orders (
    id bigint generated by default as identity primary key,
    user_id bigint,
    created_at TIMESTAMP WITH TIME ZONE,
    status varchar(30),
    total_amount numeric(12,2) CHECK (total_amount >= 0)
);

--changeset Lmncrt:004-add-new-table
CREATE TABLE public.link_orders_items (
    id bigint generated by default as identity primary key,
    order_id bigint not null,
    constraint orders_id_fk
        foreign key (order_id) references public.orders(id),
    items_id bigint not null,
    constraint items_id_fk
        foreign key (items_id) references public.items(id)
);

--changeset Lmncrt:005-add-new-table
CREATE TABLE public.order_idempotency (
    id bigint generated by default as identity primary key,
    request_key UUID unique not null,
    request_text TEXT NOT NULL,
    order_id bigint,
    constraint orders_id_fk
        foreign key (order_id) references public.orders(id)
);

--changeset Lmncrt:006-add-new-table
CREATE TABLE public.outbox (
    event_id UUID PRIMARY KEY,
    payload JSONB NOT NULL,
    published_at TIMESTAMP WITH TIME ZONE,
    order_id BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

